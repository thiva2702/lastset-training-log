const assert=require('assert');
const fs=require('fs');
const vm=require('vm');
global.__LASTSET_TEST_ONLY__=true;
vm.runInThisContext(fs.readFileSync('lastset-integrity.js','utf8'),{filename:'lastset-integrity.js'});
const T=global.LastSetIntegrityTest;
const a={profile:{name:'Lifter A',weightUnit:'kg',userId:'a'},sessions:{'2026-10-10':[{type:'resistance',exercises:[{exerciseId:'bench',sets:[{weight:80,reps:8},{weight:85,reps:6},{weight:85,reps:5}]}]}]},templates:[]};
const b={profile:{name:'Lifter B',weightUnit:'lb',userId:'b'},sessions:{'2026-10-09':[{type:'resistance',exercises:[{exerciseId:'squat',sets:[{weight:90,reps:5}]}]}]},templates:[]};
const original={version:1,activeId:'a',users:[{id:'a',name:'Lifter A',data:structuredClone(a)},{id:'b',name:'Lifter B',data:structuredClone(b)}]};
const before=structuredClone(original);
const live=structuredClone(a);
live.sessions['2026-10-11']=[{type:'mobility',activity:'Yoga',duration:30}];
const archive=T.profileArchive(original,live);
assert.equal(archive.format,'lastset-all-profiles-v1');
assert.equal(archive.users.length,2);
assert.deepStrictEqual(JSON.parse(JSON.stringify(archive.users[0].data)),live,'current in-memory data included in full export');
assert.deepStrictEqual(JSON.parse(JSON.stringify(archive.users[1].data)),b,'inactive user backup included');
const restored=T.parseProfileRestore(JSON.parse(JSON.stringify(archive)));
assert.equal(restored.length,2);
const populated=T.restoredRegistry(original,restored,(()=>{let n=0;return()=>`restored-${++n}`})());
assert.equal(populated.users.length,4);
assert.equal(populated.activeId,'a','import does not switch active profile');
assert.deepStrictEqual(JSON.parse(JSON.stringify(original)),before,'import preserves original registry');
assert.deepStrictEqual(JSON.parse(JSON.stringify(populated.users[0].data)),a,'old active data untouched');
assert.deepStrictEqual(JSON.parse(JSON.stringify(populated.users[1].data)),b,'old other profile untouched');
assert.deepStrictEqual(populated.users[2].data.sessions,live.sessions);
assert.deepStrictEqual(populated.users[3].data.sessions,b.sessions);
assert.notEqual(populated.users[2].id,'a');
assert.notEqual(populated.users[3].id,'b');
const legacy=T.parseProfileRestore(a);
assert.equal(legacy.length,1,'old single-profile exports supported');
assert.equal(T.parseProfileRestore({format:'lastset-all-profiles-v1',version:1,users:[{data:{sessions:{bad:{}}}}]}),null,'corrupted archive must reject all profiles');
assert.equal(T.parseProfileRestore({format:'lastset-all-profiles-v1',version:1,users:[]}),null,'no empty archive');
console.log('LastSet P0 non-destructive multi-profile recovery tests passed');
